// Generates Calc's function descriptions from upstream: the English strings of sc/inc/scfuncs.hrc
// (per function: description, then name and description of each parameter) joined with the
// ScFuncDescCore table aDescs of sc/source/core/data/funcdesc.cxx (opcode, flags, category, help
// id, argument count, optional flags, var args limit) into src/lo/sc/inc/scfuncs.ts. Rerun after
// an upgrade:
//   node tools/upstream/gen-scfuncs.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CORE, PORT_ROOT } from './lib.ts';

const compiler = readFileSync(join(CORE, 'include/formula/compiler.hxx'), 'utf8');
const defines = new Map<string, number>();
for (const m of compiler.matchAll(/^#define\s+(SC_OPCODE_\w+)\s+([^/\n]+?)\s*(?:\/\*.*)?$/gm)) {
  const expr = m[2]!.replace(/SC_OPCODE_\w+/g, (n) => { const v = defines.get(n); if (v === undefined) throw new Error(`unresolved ${n}`); return String(v); });
  if (!/^[\d\s()+\-xXa-fA-F]+$/.test(expr)) throw new Error(`unresolved ${m[1]} = ${m[2]}`);
  defines.set(m[1]!, Number(Function(`return (${expr});`)()));
}

const unescape = (s: string): string => JSON.parse(`"${s.replace(/\\'/g, "'")}"`) as string;

// scfuncs.hrc: const TranslateId SC_OPCODE_X_ARY[] = { NC_("ctx", "text" "text"), ... };
const hrc = readFileSync(join(CORE, 'sc/inc/scfuncs.hrc'), 'utf8');
const arys = new Map<string, string[]>();
for (const m of hrc.matchAll(/const TranslateId (SC_OPCODE_\w+_ARY)\[\]\s*=\s*\{([\s\S]*?)\n\};/g)) {
  const strings: string[] = [];
  for (const s of m[2]!.matchAll(/NC_\(\s*"[^"]*"\s*,((?:\s*"(?:[^"\\]|\\.)*")+)\s*\)/g))
    strings.push([...s[1]!.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((x) => unescape(x[1]!)).join(''));
  arys.set(m[1]!, strings);
}

const VAR_ARGS = 255;
const cxx = readFileSync(join(CORE, 'sc/source/core/data/funcdesc.cxx'), 'utf8');
const start = cxx.indexOf('static const ScFuncDescCore aDescs[] =');
const body = cxx.slice(start, cxx.indexOf('};', start));
const rows: string[] = [];
for (const m of body.matchAll(/\{\s*(SC_OPCODE_\w+)\s*,\s*ENTRY\((SC_OPCODE_\w+_ARY)\),\s*(\d+),\s*(ID_FUNCTION_GRP_\w+),\s*(HID_\w+),\s*([^,]+),\s*\{([\d,\s]*)\},\s*(\d+)\s*\}/g)) {
  const op = defines.get(m[1]!);
  if (op === undefined) throw new Error(`unknown ${m[1]}`);
  const strings = arys.get(m[2]!);
  if (!strings) throw new Error(`missing ${m[2]}`);
  const nArgs = Number(Function('VAR_ARGS', 'PAIRED_VAR_ARGS', `return (${m[6]});`)(VAR_ARGS, 2 * VAR_ARGS));
  const opt = m[7]!.split(',').map((x) => x.trim()).filter(Boolean).map(Number);
  rows.push(`  { nOpCode: ${op}, aResource: ${JSON.stringify(strings)}, nFunctionFlags: ${m[3]}, nCategory: ${m[4]}, pHelpId: '${m[5]}', nArgs: ${nArgs}, aOptionalArgs: [${opt.join(', ')}], nVarArgsLimit: ${m[8]} }, // ${m[1]}`);
}
if (rows.length < 400) throw new Error(`only ${rows.length} descriptions parsed`);

const grp = readFileSync(join(CORE, 'sc/inc/scfuncs.hxx'), 'utf8');
const grps = [...grp.matchAll(/^#define\s+(ID_FUNCTION_GRP_\w+)\s+(\d+)/gm)];
const cats = [...readFileSync(join(CORE, 'sc/inc/compiler.hrc'), 'utf8').matchAll(/NC_\("RID_FUNCTION_CATEGORIES",\s*"([^"]*)"\)/g)].map((x) => x[1]!);

const out = `// SPDX-License-Identifier: MPL-2.0
// @upstream sc/inc/scfuncs.hrc faithful
// @upstream sc/inc/scfuncs.hxx faithful
// @upstream sc/inc/compiler.hrc faithful
// Generated by tools/upstream/gen-scfuncs.ts; do not edit. The function wizard's descriptions in
// their en-US source form: per function the ScFuncDescCore entry of funcdesc.cxx's aDescs table
// with its SC_OPCODE_*_ARY strings from scfuncs.hrc inlined as aResource (the description, then
// name and description of each parameter). Sorted by opcode as upstream's table.

${grps.map((g) => `export const ${g[1]} = ${g[2]};`).join('\n')}

/** RID_FUNCTION_CATEGORIES (compiler.hrc): the category names, indexed by ID_FUNCTION_GRP_* - 1. */
export const RID_FUNCTION_CATEGORIES: readonly string[] = ${JSON.stringify(cats)};

export interface ScFuncDescCore {
  /** An opcode from include/formula/compiler.hxx. */
  readonly nOpCode: number;
  /** The strings: description, then name and description per parameter. */
  readonly aResource: readonly string[];
  /** Bit 1: suppressed entirely; bit 2: hidden in the Function Wizard unless used. */
  readonly nFunctionFlags: number;
  /** One of ID_FUNCTION_GRP_*. */
  readonly nCategory: number;
  readonly pHelpId: string;
  /** Parameter count, VAR_ARGS(+n) or PAIRED_VAR_ARGS(+n). */
  readonly nArgs: number;
  /** Per parameter: 1 if optional. */
  readonly aOptionalArgs: readonly number[];
  /** Maximum (variable) parameter count, or 0. */
  readonly nVarArgsLimit: number;
}

export const aDescs: readonly ScFuncDescCore[] = [
${rows.join('\n')}
];
`;
writeFileSync(join(PORT_ROOT, 'sc/inc/scfuncs.ts'), out);
console.log(`${rows.length} function descriptions`);
