// Generates the formula module's data ports from upstream: the opcodes (include/formula/compiler.hxx
// and opcode.hxx) into src/lo/include/formula/opcode.ts, and the function name tables
// (formula/inc/core_resource.hrc) into src/lo/formula/inc/core_resource.ts. Rerun after an upgrade:
//   node tools/upstream/gen-formula.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CORE, PORT_ROOT } from './lib.ts';

const compiler = readFileSync(join(CORE, 'include/formula/compiler.hxx'), 'utf8');
const defines = new Map<string, number>();
for (const m of compiler.matchAll(/^#define\s+(SC_OPCODE_\w+)\s+([^/\n]+?)\s*(?:\/\*.*)?$/gm)) {
  // values are numbers, other defines or simple sums/differences of them
  const expr = m[2]!.replace(/SC_OPCODE_\w+/g, (n) => { const v = defines.get(n); if (v === undefined) throw new Error(`unresolved ${n}`); return String(v); });
  if (!/^[\d\s()+\-xXa-fA-F]+$/.test(expr)) throw new Error(`unresolved ${m[1]} = ${m[2]}`);
  defines.set(m[1]!, Number(Function(`return (${expr});`)()));
}

const opcode = readFileSync(join(CORE, 'include/formula/opcode.hxx'), 'utf8');
const ops: [string, number][] = [];
for (const m of opcode.matchAll(/^\s+(oc\w+)\s*=\s*(SC_OPCODE_\w+),?/gm)) {
  const v = defines.get(m[2]!);
  if (v === undefined) throw new Error(`unknown ${m[2]}`);
  ops.push([m[1]!, v]);
}

let out = `// SPDX-License-Identifier: MPL-2.0
// @upstream include/formula/opcode.hxx faithful
// @upstream include/formula/compiler.hxx faithful
// Generated by tools/upstream/gen-formula.ts; do not edit. The OpCode enum: one constant per
// opcode with upstream's name (ocSum), and the SC_OPCODE_* ranges compiler.hxx defines.

export type OpCode = number;

`;
for (const [n, v] of ops) out += `export const ${n}: OpCode = ${v};\n`;
out += `\n/** The opcode names by value (OpCodeEnumToString without the "oc"). */\nexport const OpCodeNames: Readonly<Record<number, string>> = {\n`;
const seen = new Set<number>();
for (const [n, v] of ops) { if (seen.has(v)) continue; seen.add(v); out += `  ${v}: '${n}',\n`; }
out += '};\n\n';
for (const [n, v] of defines) if (/^SC_OPCODE_(START|STOP)_|_LAST_OPCODE_ID$/.test(n)) out += `export const ${n} = ${v};\n`;
writeFileSync(join(PORT_ROOT, 'include/formula/opcode.ts'), out);

const hrc = readFileSync(join(CORE, 'formula/inc/core_resource.hrc'), 'utf8');
const tables = ['RID_STRLIST_FUNCTION_NAMES_ENGLISH_ODFF', 'RID_STRLIST_FUNCTION_NAMES_ENGLISH_OOXML', 'RID_STRLIST_FUNCTION_NAMES_ENGLISH_PODF',
  'RID_STRLIST_FUNCTION_NAMES_ENGLISH_API', 'RID_STRLIST_FUNCTION_NAMES_ENGLISH', 'RID_STRLIST_FUNCTION_NAMES', 'RID_STRLIST_FUNCTION_NAMES_SYMBOLS'];
let res = `// SPDX-License-Identifier: MPL-2.0
// @upstream formula/inc/core_resource.hrc faithful
// Generated by tools/upstream/gen-formula.ts; do not edit. The function name tables: name and
// opcode pairs per grammar. RID_STRLIST_FUNCTION_NAMES holds the translatable names in their
// en-US source form (the UI names).

`;
for (const t of tables) {
  const start = hrc.indexOf(`${t}[] =`);
  const end = hrc.indexOf('};', start);
  const body = hrc.slice(start, end);
  const rows: [string, number][] = [];
  for (const m of body.matchAll(/\{\s*(?:NC_\("[^"]*",\s*)?"((?:[^"\\]|\\.)*)"\)?\s*,\s*(SC_OPCODE_\w+)\s*\}/g)) {
    const v = defines.get(m[2]!);
    if (v === undefined) throw new Error(`unknown ${m[2]}`);
    rows.push([m[1]!, v]);
  }
  res += `export const ${t}: readonly (readonly [string, number])[] = [\n${rows.map(([s, v]) => `  [${JSON.stringify(s)}, ${v}],`).join('\n')}\n];\n\n`;
}
writeFileSync(join(PORT_ROOT, 'formula/inc/core_resource.ts'), res);
console.log(`${ops.length} opcodes, ${tables.length} name tables`);

// ScParameterClassification (sc/source/core/tool/parclass.cxx): the raw table and the lookup.
const parclass = readFileSync(join(CORE, 'sc/source/core/tool/parclass.cxx'), 'utf8');
const rawStart = parclass.indexOf('ScParameterClassification::pRawData[] =');
const rawEnd = parclass.indexOf('};', rawStart);
const rows: string[] = [];
for (const m of parclass.slice(rawStart, rawEnd).matchAll(/\{\s*(oc\w+),\s*\{\{([^}]*)\},\s*(\d+),\s*(\w+)\s*\}\s*\}/g)) {
  const params = m[2]!.split(',').map((x) => x.trim()).filter(Boolean);
  rows.push(`  [${m[1]}, [${params.map((p) => `P.${p}`).join(', ')}], ${m[3]}, P.${m[4]}],`);
}
const ocs = [...new Set(rows.map((r) => /\[(oc\w+)/.exec(r)![1]!))].sort();
const pc = `// SPDX-License-Identifier: MPL-2.0
// @upstream sc/source/core/tool/parclass.cxx partial
// @upstream sc/source/core/inc/parclass.hxx partial
// Generated by tools/upstream/gen-formula.ts; do not edit. ScParameterClassification: the
// parameter and return classes of the opcodes (the raw table and GetParameterType). Legacy
// (non-UNO) add-in parameter types and the documentation generator are left out.
import { ParamClass as P, type FormulaToken, type ParamClass } from '../../../../formula/source/core/api/token.ts';
import { ScAddInArgumentType } from '../../../inc/addincol.ts';
import { GetAddInCollection } from './addincol.ts';
import { ${ocs.join(', ')}, ocExternal, ocMacro, SC_OPCODE_LAST_OPCODE_ID } from '../../../../include/formula/opcode.ts';

const nMaxParams = 7;
type RawData = [number, ParamClass[], number, ParamClass];

// { OpCode, {{ ParamClass, ... }, nRepeatLast, ReturnClass }},
const pRawData: RawData[] = [
${rows.join('\n')}
];

interface RunData { nParam: ParamClass[]; nRepeatLast: number; eReturn: ParamClass; nMinParams: number; bHasForceArray: boolean }
let pData: (RunData | undefined)[] | null = null;

function Init(): (RunData | undefined)[] {
  if (pData) return pData;
  pData = [];
  // init from specified static data above
  for (const [eOp, aParam, nRepeatLast, eReturn] of pRawData) {
    if (eOp > SC_OPCODE_LAST_OPCODE_ID) continue;
    const nParam: ParamClass[] = Array.from({ length: nMaxParams }, (_, j) => aParam[j] ?? P.Unknown);
    const pRun: RunData = { nParam, nRepeatLast, eReturn, nMinParams: 0, bHasForceArray: false };
    // fill 0-initialized fields with real values
    if (nRepeatLast) {
      for (let j = 0; j < nMaxParams; ++j) {
        if (nParam[j]) pRun.nMinParams = j + 1;
        else if (j >= nRepeatLast) nParam[j] = nParam[j - nRepeatLast]!;
        else nParam[j] = P.Unknown;
      }
    } else {
      for (let j = 0; j < nMaxParams; ++j) {
        if (!nParam[j]) {
          if (j === 0 || nParam[j - 1] !== P.Bounds) pRun.nMinParams = j;
          nParam[j] = P.Bounds;
        }
      }
      if (!pRun.nMinParams && nParam[nMaxParams - 1] !== P.Bounds) pRun.nMinParams = nMaxParams;
    }
    pRun.bHasForceArray = nParam.some((j) => j === P.ForceArray || j === P.ReferenceOrForceArray);
    pData[eOp] = pRun;
  }
  return pData;
}

export const ScParameterClassification = {
  /** Get one parameter type for function eOp.
      @param nParameter
          Which parameter, 0-based. SAL_MAX_UINT16 (0xffff) for return value of function. */
  GetParameterType(pToken: FormulaToken, nParameter: number): ParamClass {
    const eOp = pToken.GetOpCode();
    switch (eOp) {
      case ocExternal:
        return ScParameterClassification.GetExternalParameterType(pToken, nParameter);
      case ocMacro:
        return nParameter === 0xffff ? P.Value : P.Reference;
      default:
    }
    if (eOp >= 0 && eOp <= SC_OPCODE_LAST_OPCODE_ID) {
      const pRun = Init()[eOp];
      if (!pRun) return nParameter === 0xffff ? P.Unknown : P.Value;
      let eType: ParamClass;
      let nRepeat: number;
      if (nParameter === 0xffff) eType = pRun.eReturn;
      else if (nParameter < nMaxParams) eType = pRun.nParam[nParameter]!;
      else if ((nRepeat = pRun.nRepeatLast) > 0) {
        // The usual case is 1 repeated parameter, we don't need to
        // calculate that on each call.
        const nParam = nRepeat > 1 ? pRun.nMinParams - ((nParameter - pRun.nMinParams) % nRepeat) : pRun.nMinParams;
        return pRun.nParam[nParam]!;
      } else eType = P.Bounds;
      return eType === P.Unknown ? P.Value : eType;
    }
    return P.Unknown;
  },

  /** The parameter class of an add-in function's parameter (GetExternalParameterType); legacy
      add-ins are not supported. */
  GetExternalParameterType(pToken: FormulaToken, nParameter: number): ParamClass {
    let eRet: ParamClass = P.Unknown;
    if (nParameter === 0xffff) return eRet;

    // similar to ScInterpreter::ScExternal()
    const aFuncName = pToken.GetExternal().toUpperCase(); // programmatic name
    const aUnoName = GetAddInCollection().FindFunction(aFuncName, false);

    if (aUnoName) {
      // the relevant parts of ScUnoAddInCall without having to create one
      const pFuncData = GetAddInCollection().GetFuncData(aUnoName); // need fully initialized data
      if (pFuncData) {
        const nCount = pFuncData.GetArgumentCount();
        if (nCount <= 0) eRet = P.Bounds;
        else {
          const pArgs = pFuncData.GetArguments();
          if (nParameter >= nCount && pArgs[nCount - 1]!.eType === ScAddInArgumentType.SC_ADDINARG_VARARGS) eRet = P.Value;
          // last arg is sequence, optional "any"s, we simply can't
          // determine the type
          if (eRet === P.Unknown) {
            if (nParameter >= nCount) eRet = P.Bounds;
            else {
              switch (pArgs[nParameter]!.eType) {
                case ScAddInArgumentType.SC_ADDINARG_INTEGER:
                case ScAddInArgumentType.SC_ADDINARG_DOUBLE:
                case ScAddInArgumentType.SC_ADDINARG_STRING:
                  eRet = P.Value;
                  break;
                default:
                  eRet = P.Reference;
              }
            }
          }
        }
      }
    }
    return eRet;
  },

  /** Whether OpCode has a parameter of type ForceArray or ReferenceOrForceArray. */
  HasForceArray(eOp: number): boolean {
    return eOp >= 0 && eOp <= SC_OPCODE_LAST_OPCODE_ID ? (Init()[eOp]?.bHasForceArray ?? false) : false;
  },
};
`;
writeFileSync(join(PORT_ROOT, 'sc/source/core/tool/parclass.ts'), pc);
console.log(`${rows.length} parameter classifications`);
