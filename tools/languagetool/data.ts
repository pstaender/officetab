// LanguageTool's data for the browser, as the ported engine reads it from the classpath:
// - resources in LanguageTool's repository (rules, disambiguation, word lists) are served by
//   jsDelivr from the pinned tag, unchanged; their classpath paths are listed with their module;
// - binary data from Maven artifacts (tagger and speller dictionaries, OpenNLP models), which
//   Maven Central does not serve to browsers, is unpacked into public/languagetool/ (git-ignored),
//   checked against the pinned SHA-1, and served with the application.
// Writes src/languagetool/generated/resources.json. Usage: node tools/languagetool/data.ts [--force]
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { readZip } from '../../src/lo/package/source/zipapi/zip.ts';
import { LT_ROOT, ROOT, upstreams } from '../upstream/lib.ts';

interface Artifact { id: string; sha1: string; include: string; exclude?: string }
const pins = (await import(join(LT_ROOT, 'upstream.json'), { with: { type: 'json' } })).default as { $data: { artifacts: Artifact[] } };
const OUT = join(ROOT, 'public/languagetool');
const force = process.argv.includes('--force');

const local: string[] = [];
for (const a of pins.$data.artifacts) {
  const [group, name, version] = a.id.split(':') as [string, string, string];
  const url = `https://repo1.maven.org/maven2/${group.replace(/\./g, '/')}/${name}/${version}/${name}-${version}.jar`;
  const stamp = join(OUT, '.artifacts', `${name}-${version}.sha1`);
  let entries: [string, Uint8Array][] | null = null;
  if (force || !existsSync(stamp)) {
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${url}: ${res.status}`);
    const jar = new Uint8Array(await res.arrayBuffer());
    const sha1 = createHash('sha1').update(jar).digest('hex');
    if (sha1 !== a.sha1) throw new Error(`${url}: SHA-1 ${sha1}, pinned ${a.sha1}`);
    entries = [...(await readZip(jar))];
  }
  const inc = new RegExp(a.include), exc = a.exclude ? new RegExp(a.exclude) : null;
  if (entries) {
    for (const [path, data] of entries) {
      if (!inc.test(path) || exc?.test(path)) continue;
      mkdirSync(dirname(join(OUT, path)), { recursive: true });
      writeFileSync(join(OUT, path), data);
    }
    mkdirSync(dirname(stamp), { recursive: true });
    writeFileSync(stamp, `${a.sha1}\n`);
    console.log(`${a.id}: unpacked`);
  }
  // The stamp's artifact is unpacked: list what it brought.
  const listed = entries ? entries.map(([p]) => p) : execFileSync('find', ['.', '-type', 'f', '-not', '-path', './.artifacts/*'], { cwd: OUT, encoding: 'utf8' }).split('\n').map((p) => p.replace(/^\.\//, ''));
  for (const p of listed) if (p && inc.test(p) && !exc?.test(p) && !local.includes(`/${p}`)) local.push(`/${p}`);
}

// The repository's resources by module (only the modules in the sparse checkout).
const lt = upstreams().find((u) => u.id === 'languagetool')!;
if (!existsSync(join(lt.checkout, '.git'))) {
  // A build without the upstream checkout keeps the committed manifest.
  console.log('upstream/languagetool is missing: the resource manifest is kept (npm run upstream:fetch to regenerate it).');
  process.exit(0);
}
const modules: Record<string, string> = {};
const files = execFileSync('git', ['-C', lt.checkout, 'ls-tree', '-r', '--name-only', lt.commit, '--', 'languagetool-core/src/main/resources', 'languagetool-language-modules/en/src/main/resources', 'languagetool-language-modules/de/src/main/resources'], { encoding: 'utf8' }).split('\n').filter(Boolean);
const resources: Record<string, string> = {};
for (const f of files) {
  const m = /^(.*\/src\/main\/resources)(\/.*)$/.exec(f)!;
  const mod = m[1]!.split('/src/main/resources')[0]!;
  modules[mod] = m[1]!;
  resources[m[2]!] = mod;
}
const manifest = {
  $comment: 'Generated by tools/languagetool/data.ts: where each classpath resource of the ported LanguageTool is loaded from.',
  cdn: `https://cdn.jsdelivr.net/gh/languagetool-org/languagetool@${lt.tag}`,
  modules,
  resources,
  local: local.sort(),
};
mkdirSync(join(LT_ROOT, 'generated'), { recursive: true });
writeFileSync(join(LT_ROOT, 'generated/resources.json'), `${JSON.stringify(manifest, null, 1)}\n`);
console.log(`${Object.keys(resources).length} repository resources, ${local.length} local files`);
