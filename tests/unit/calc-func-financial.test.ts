describe('Calc financial functions: upstream test sheets', () => {
  for (const [f, exp] of CASES) {
    it(f, () => {
      const doc = newDoc();
      if (typeof exp === 'number') {
        expect(calc(doc, f)).not.toMatch(/^(Err:|#)/);
        const v = calcValue(doc, f);
        expect(Math.abs(v - exp)).toBeLessThanOrEqual(1e-9 * Math.max(1, Math.abs(exp)));
      } else expect(calc(doc, f)).toBe(exp);
    });
  }
});

describe('Calc financial functions', () => {
  it('reads cash flows from ranges', () => {
    const doc = newDoc();
    putAll(doc, { A1: -10000, A2: 5000, A3: 5000, A4: 5000, B1: 10, C1: 20, D1: 30, B2: 10, C2: 'x', D2: 20 });
    expect(calcValue(doc, '=IRR(A1:A4)')).toBeCloseTo(0.233751928528259, 12);
    expect(calcValue(doc, '=IRR(A1:A4;0.2)')).toBeCloseTo(0.233751928528259, 12);
    expect(calcValue(doc, '=MIRR(A1:A4;0.065;0.1)')).toBeCloseTo(((5000 / 1.1 + 5000 / 1.21 + 5000 / 1.331) / 10000 * 1.331) ** (1 / 3) - 1, 12);
    expect(calcValue(doc, '=NPV(0.0875;B1:D1)')).toBeCloseTo(49.432121038173, 10);
    // Text cells are skipped; single references and values mix.
    expect(calcValue(doc, '=NPV(0.0875;B2:D2;30)')).toBeCloseTo(49.432121038173 - 20 / 1.0875 ** 2 + 20 / 1.0875 ** 2, 10);
    expect(calcValue(doc, '=NPV(0.0875;B1;C1;D1)')).toBeCloseTo(49.432121038173, 10);
    // A two-dimensional range is read row by row.
    putAll(doc, { F1: 10, G1: 20, F2: 30, G2: 40 });
    expect(calcValue(doc, '=NPV(0.1;F1:G2)')).toBeCloseTo(10 / 1.1 + 20 / 1.1 ** 2 + 30 / 1.1 ** 3 + 40 / 1.1 ** 4, 10);
    expect(calc(doc, '=IRR(A1)')).toBe('Err:504');
  });

  it('formats results as currency and percent', () => {
    const doc = newDoc();
    expect(calc(doc, '=PMT(0.0199/12;36;25000)')).toMatch(/715\.96/);
    expect(calc(doc, '=RATE(10;-1000;6500)')).toBe('8.71%');
    expect(calc(doc, '=NPER(0.0525;-200;1500)')).toBe('9.780722987524');
  });
});
