export type HtmlTokenId = (typeof HtmlTokenId)[keyof typeof HtmlTokenId];

export function isOffToken(nToken: HtmlTokenId): boolean {
  return (nToken === HtmlTokenId.NONE || nToken >= HtmlTokenId.ONOFF_START) ? (1 & nToken) === 1 : false;
}

export function getOnToken(nToken: HtmlTokenId): HtmlTokenId {
  return (nToken === HtmlTokenId.NONE || nToken >= HtmlTokenId.ONOFF_START) ? (~1 & nToken) as HtmlTokenId : nToken;
}
