export type SmTokenType = (typeof T)[keyof typeof T];

export interface SmTokenTableEntry { aIdent: string; eType: SmTokenType; cMathChar: number; nGroup: TG; nLevel: number }

export class SmToken {
  aText: string; // token text
  eType: SmTokenType; // token info
  cMathChar: string;
  // parse-help info
  nGroup: TG;
  nLevel: number;

  constructor(eTokenType: SmTokenType = T.TUNKNOWN, cMath = 0, rText = '', nTokenGroup: TG = TG.NONE, nTokenLevel = 0) {
    this.aText = rText;
    this.eType = eTokenType;
    this.cMathChar = cMath ? String.fromCodePoint(cMath) : '';
    this.nGroup = nTokenGroup;
    this.nLevel = nTokenLevel;
  }

  clone(): SmToken {
    const t = new SmToken(this.eType, 0, this.aText, this.nGroup, this.nLevel);
    t.cMathChar = this.cMathChar;
    return t;
  }

  /** operator=(const SmTokenTableEntry&) */
  assign(e: SmTokenTableEntry): void {
    this.aText = e.aIdent;
    this.eType = e.eType;
    this.cMathChar = e.cMathChar ? String.fromCodePoint(e.cMathChar) : '';
    this.nGroup = e.nGroup;
    this.nLevel = e.nLevel;
  }

  setChar(c: number | string): void { this.cMathChar = typeof c === 'number' ? (c ? String.fromCodePoint(c) : '') : c; }
}
