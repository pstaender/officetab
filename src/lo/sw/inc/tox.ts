// SwTOXMark and SwTOXType: the entries of a table of contents, alphabetical index or user-defined
// index, and the index types they belong to. Reduced: a mark is not an SfxPoolItem listening to
// its type; it is an immutable value on the text it marks (RES_TXTATR_TOXMARK), so undo snapshots
// can share it, and changing a mark replaces it. A mark with an alternative text sits on a
// placeholder character (SwTextTOXMark::HasDummyChar; CH_TXTATR_BREAKWORD here, CH_TXTATR_INWORD
// upstream); a mark without one covers the runs of its text, within one paragraph.
import { TOXTypes } from './toxe.ts';

/** Index types (SwTOXType): the type of index and its name; user-defined indexes are told apart by name. */
export class SwTOXType {
  m_aName: string;
  m_eType: TOXTypes;
  constructor(eTyp: TOXTypes, aName: string) {
    this.m_aName = aName;
    this.m_eType = eTyp;
  }
  GetTypeName(): string { return this.m_aName; }
  GetType(): TOXTypes { return this.m_eType; }
}

/** SwDoc::SwDoc (docnew.cxx): the index types every document has, with their ShellResource names. */
export function DefaultTOXTypes(): SwTOXType[] {
  return [
    new SwTOXType(TOXTypes.TOX_CONTENT, 'Table of Contents'),
    new SwTOXType(TOXTypes.TOX_INDEX, 'Alphabetical Index'),
    new SwTOXType(TOXTypes.TOX_USER, 'User-Defined'),
  ];
}

/** Entry of content index, alphabetical index or user defined index */
export class SwTOXMark {
  m_pType: SwTOXType;
  m_aAltText = ''; // Text of caption is different.
  m_aPrimaryKey = '';
  m_aSecondaryKey = '';
  // three more strings for phonetic sorting
  m_aTextReading = '';
  m_aPrimaryKeyReading = '';
  m_aSecondaryKeyReading = '';
  m_nLevel = 0;
  m_bAutoGenerated = false; // generated using a concordance file
  m_bMainEntry = false; // main entry emphasized by character style

  constructor(pTyp: SwTOXType, rCopy?: SwTOXMark) {
    this.m_pType = pTyp;
    if (rCopy) {
      this.m_aPrimaryKey = rCopy.m_aPrimaryKey;
      this.m_aSecondaryKey = rCopy.m_aSecondaryKey;
      this.m_aTextReading = rCopy.m_aTextReading;
      this.m_aPrimaryKeyReading = rCopy.m_aPrimaryKeyReading;
      this.m_aSecondaryKeyReading = rCopy.m_aSecondaryKeyReading;
      this.m_nLevel = rCopy.m_nLevel;
      this.m_bAutoGenerated = rCopy.m_bAutoGenerated;
      this.m_bMainEntry = rCopy.m_bMainEntry;
      // Copy AlternativString
      this.m_aAltText = rCopy.m_aAltText;
    }
  }

  /** SwTOXMark( const SwTOXMark& rCopy ): changing a mark replaces it with a changed copy. */
  Clone(): SwTOXMark { return new SwTOXMark(this.m_pType, this); }

  /**
   * The alternative text, or the text the mark covers: [nStart, nEnd) of its paragraph's text
   * (SwTextNode::GetExpandText, here without the placeholder characters of fields).
   */
  GetText(rText?: string, nStart = 0, nEnd = 0): string {
    if (this.m_aAltText) return this.m_aAltText;
    if (rText !== undefined) return rText.slice(nStart, nEnd).replace(/\u0001/g, '');
    return '';
  }

  IsAlternativeText(): boolean { return this.m_aAltText.length > 0; }
  GetAlternativeText(): string { return this.m_aAltText; }
  SetAlternativeText(rAlt: string): void { this.m_aAltText = rAlt; }
  // content or user defined index
  SetLevel(nLevel: number): void { this.m_nLevel = nLevel; }
  GetLevel(): number { return this.m_nLevel; }
  // for alphabetical index only
  SetPrimaryKey(rStr: string): void { this.m_aPrimaryKey = rStr; }
  SetSecondaryKey(rStr: string): void { this.m_aSecondaryKey = rStr; }
  SetTextReading(rStr: string): void { this.m_aTextReading = rStr; }
  SetPrimaryKeyReading(rStr: string): void { this.m_aPrimaryKeyReading = rStr; }
  SetSecondaryKeyReading(rStr: string): void { this.m_aSecondaryKeyReading = rStr; }
  GetPrimaryKey(): string { return this.m_aPrimaryKey; }
  GetSecondaryKey(): string { return this.m_aSecondaryKey; }
  GetTextReading(): string { return this.m_aTextReading; }
  GetPrimaryKeyReading(): string { return this.m_aPrimaryKeyReading; }
  GetSecondaryKeyReading(): string { return this.m_aSecondaryKeyReading; }
  IsAutoGenerated(): boolean { return this.m_bAutoGenerated; }
  SetAutoGenerated(bSet: boolean): void { this.m_bAutoGenerated = bSet; }
  IsMainEntry(): boolean { return this.m_bMainEntry; }
  SetMainEntry(bSet: boolean): void { this.m_bMainEntry = bSet; }
  GetTOXType(): SwTOXType { return this.m_pType; }
}
